export const getCraftsmanReviews = (craftsmanId: string): CraftsmanReview[] => {
  return craftsmenReviews
    .filter((review) => review.craftsmanId === craftsmanId)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
};

export const getRatingDistribution = (
  craftsmanId: string,
): RatingDistribution[] => {
  const values = ratingDistributionByCraftsman[craftsmanId] ?? [0, 0, 0, 0, 0];

  return values.map((percent, index) => ({
    stars: 5 - index,
    percent,
  }));
};

export const getReviewInsights = (craftsmanId: string): ReviewInsight[] => {
  const reviews = getCraftsmanReviews(craftsmanId);
  const counts = new Map<string, number>();

  reviews.forEach((review) => {
    review.tags.forEach((tag) => {
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    });
  });

  return [...counts.entries()]
    .map(([label, count]) => ({ label, count }))
    .sort((a, b) => b.count - a.count)
    .slice(0, 4);
};